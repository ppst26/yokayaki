BEGIN;

UPDATE public.menu_items
SET category = 'ทานเล่น'
WHERE category = 'กินเล่น';

-- ย้ายเมนูในหมวดทดสอบไป "อื่นๆ" แล้วหมวดทดสอบจะหายจากตัวกรองเอง
UPDATE public.menu_items
SET category = 'อื่นๆ'
WHERE category = 'ทดสอบ';

COMMIT;
